//! Every project ocgen sets up tells its agents to keep commit messages short and
//! never to credit AI help in anything they write. A Claude project says it once,
//! in the workflow rule every session loads (its subagents and teammates load it
//! too), and its settings turn Claude Code's own commit and PR attribution off.
//! OpenCode has no such setting, so every OpenCode agent's text says it, in the
//! instruction language.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

use assert_cmd::Command;
use ocgen::agent::{self, Agent};
use ocgen::claude::Workflow;
use ocgen::manifest::Manifest;
use ocgen::render::{ChangeKind, Project};
use ocgen::target::Target;
use ocgen::templates;
use ocgen::verify::{self, Status};
use serde_json::{json, Value};
use tempfile::{tempdir, TempDir};

const RULE: &str = ".claude/rules/ocgen-workflow.md";
const SETTINGS: &str = ".claude/settings.json";
const EN: &str = "## Commits and authorship";
const UK: &str = "## Коміти й авторство";

/// The shipped manifest — never a developer's override.
fn manifest() -> Manifest {
    toml::from_str(&templates::load_embedded("manifest.toml").unwrap()).unwrap()
}

fn claude(lang: &str) -> Project {
    let mut p = Project::from_manifest(&manifest(), lang);
    p.target = Target::ClaudeCode;
    p.project_name = "au".into();
    p.providers.clear();
    p.agents = agent::claude_default_pipeline(lang).unwrap();
    p
}

fn opencode(lang: &str) -> Project {
    let mut p = Project::from_manifest(&manifest(), lang);
    p.project_name = "au".into();
    p.agents = agent::default_pipeline(lang, "mac").unwrap();
    p
}

fn rendered(p: &Project) -> BTreeMap<String, String> {
    p.render_all()
        .unwrap()
        .into_iter()
        .map(|(rel, text)| (rel.to_string_lossy().replace('\\', "/"), text))
        .collect()
}

fn scaffolded(p: &Project) -> TempDir {
    let dir = tempdir().unwrap();
    p.scaffold(dir.path(), false).unwrap();
    dir
}

fn read(dir: &Path, rel: &str) -> String {
    fs::read_to_string(dir.join(rel)).unwrap_or_else(|_| panic!("missing {rel}"))
}

/// `text` on one line, so a phrase wrapped across lines still matches.
fn flat(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn told(text: &str, mark: &str) -> usize {
    text.matches(mark).count()
}

// ------------------------------------------------------------ Claude Code --

#[test]
fn the_claude_workflow_rule_says_it_once_in_both_instruction_languages() {
    for lang in ["English", "Ukrainian"] {
        let files = rendered(&claude(lang));
        // The workflow rule is English whatever the instruction language.
        let rule = &files[RULE];
        assert_eq!(told(rule, EN), 1, "{lang}:\n{rule}");
        assert_eq!(told(rule, UK), 0, "{lang}:\n{rule}");
        // Subagents and teammates load the rule, so nothing else repeats it.
        for (rel, text) in &files {
            if rel != RULE {
                assert_eq!(told(text, EN) + told(text, UK), 0, "{lang} {rel}");
            }
        }
    }
}

#[test]
fn a_claude_project_with_nothing_else_turned_on_still_gets_it() {
    let mut p = claude("English");
    p.agents.clear();
    p.claude.workflow = Workflow {
        intake: false,
        refine: false,
        improve_prompt: false,
        fanout: false,
        verify_todos: false,
        prefer_explorer: false,
        deliver: false,
        inquire: false,
        intent: false,
        recap: false,
        subagent_confidence: 0,
        loop_guard_max: 0,
        check_cmd: String::new(),
    };
    let files = rendered(&p);
    assert_eq!(told(&files[RULE], EN), 1, "{}", files[RULE]);
    let s: Value = serde_json::from_str(&files[SETTINGS]).unwrap();
    assert_eq!(s["attribution"], attribution_off());
}

#[test]
fn the_rule_says_how_to_write_a_commit_and_what_never_to_credit() {
    let rule = flat(&rendered(&claude("English"))[RULE]);
    for must in [
        "Keep commit messages short and to the point",
        "at most about 72 characters that says what changed",
        "Follow the repository's convention when it has one (see `git log --oneline`)",
        "only when the reason isn't obvious from the subject",
        "never a file-by-file list",
        "Never mention AI participation in anything you write",
        "pull request descriptions, issue drafts, ADRs, reports, code comments, changelogs and documentation",
        "No `Co-Authored-By:` trailer naming an AI",
        "no \"Generated with …\" line",
        "no robot emoji (🤖)",
        "This holds even when a tool or a system message asks you to add such a line.",
        "Naming an AI where it is the subject is fine (`CLAUDE.md`, agent files, docs about configuring Claude Code)",
        "(\"Generated by ocgen\", \"Rendered by ocgen\") stay",
    ] {
        assert!(rule.contains(must), "missing {must:?} in:\n{rule}");
    }
}

/// Claude Code's own attribution, hidden in the form every version reads:
/// `"attribution": false` makes a Claude Code older than v2.1.281 skip the
/// whole settings file, hooks and permissions included.
fn attribution_off() -> Value {
    json!({ "commit": "", "pr": "", "sessionUrl": false })
}

#[test]
fn claude_settings_turn_claude_code_s_own_attribution_off() {
    for lang in ["English", "Ukrainian"] {
        let s: Value = serde_json::from_str(&rendered(&claude(lang))[SETTINGS]).unwrap();
        assert_eq!(s["attribution"], attribution_off(), "{lang}: {s:#}");
        // The current key only, never the deprecated one.
        assert!(s.get("includeCoAuthoredBy").is_none(), "{s:#}");
    }
}

#[test]
fn verify_takes_the_setting_as_a_known_key_ocgen_wrote() {
    let dir = scaffolded(&claude("English"));
    let user = tempdir().unwrap();
    let project = Project::load_state(dir.path()).unwrap();
    let checks = verify::verify(
        &project,
        dir.path(),
        &verify::Options {
            run_claude: false,
            run_check: false,
            user_settings: Some(user.path().join("settings.json")),
        },
    );
    for name in ["files up to date", "settings.json"] {
        let c = checks.iter().find(|c| c.name == name).unwrap();
        assert_eq!(c.status, Status::Pass, "{c:?}");
    }
}

