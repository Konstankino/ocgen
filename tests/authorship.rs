/// How ocgen fingerprints a file it wrote: FNV-1a, 64-bit.
fn fingerprint(content: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in content.as_bytes() {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{h:016x}")
}

/// `text` without the section that starts at `mark`, as ocgen wrote it before
/// the section existed: the section runs up to the next block (`until`).
fn without_section(text: &str, mark: &str, until: &str) -> String {
    let start = text.find(mark).unwrap();
    let end = start + text[start..].find(until).unwrap();
    format!("{}{}", &text[..start], &text[end..])
}

/// Turn the project in `dir` into what an ocgen from before the change wrote,
/// recorded as ocgen's own output. Returns the files that changed.
fn as_made_before(dir: &Path, target: Target) -> BTreeSet<String> {
    let state_rel = target.state_file();
    let mut state: Value = serde_json::from_str(&read(dir, state_rel)).unwrap();
    let rels: Vec<String> = state["generated"]
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    let mut changed = BTreeSet::new();
    for rel in rels {
        let text = read(dir, &rel);
        let old = if rel == SETTINGS {
            let mut s: Value = serde_json::from_str(&text).unwrap();
            s.as_object_mut().unwrap().remove("attribution");
            format!("{}\n", serde_json::to_string_pretty(&s).unwrap())
        } else if text.contains(EN) && rel == RULE {
            without_section(&text, EN, "\n## ")
        } else if let Some(mark) = [EN, UK].into_iter().find(|m| text.contains(m)) {
            without_section(&text, mark, "<mindset>")
        } else {
            continue;
        };
        assert!(old != text, "{rel}");
        fs::write(dir.join(&rel), &old).unwrap();
        state["generated"][&rel] = json!(fingerprint(&old));
        changed.insert(rel);
    }
    fs::write(
        dir.join(state_rel),
        serde_json::to_string_pretty(&state).unwrap(),
    )
    .unwrap();
    changed
}

#[test]
fn a_project_made_before_gets_it_from_doctor_and_nothing_else_changes() {
    for p in [
        claude("Ukrainian"),
        opencode("Ukrainian"),
        opencode("English"),
    ] {
        let target = p.target;
        let dir = scaffolded(&p);
        let changed = as_made_before(dir.path(), target);
        match target {
            Target::ClaudeCode => assert_eq!(
                changed,
                BTreeSet::from([RULE.to_string(), SETTINGS.to_string()])
            ),
            Target::OpenCode => {
                assert!(changed.iter().all(|r| r.starts_with(".opencode/")));
                assert!(changed.len() > p.agents.len(), "{changed:?}");
            }
        }

        // What doctor would change: exactly those files, none edited by hand.
        let loaded = Project::load_state(dir.path()).unwrap();
        let plan = loaded.plan_changes(dir.path()).unwrap();
        let modified: BTreeSet<String> = plan
            .iter()
            .filter(|c| c.kind != ChangeKind::Unchanged)
            .map(|c| {
                assert_eq!(c.kind, ChangeKind::Modified, "{}", c.rel);
                assert_eq!(c.hand_edited, Some(false), "{}", c.rel);
                c.rel.clone()
            })
            .collect();
        assert_eq!(modified, changed, "{target:?}");

        Command::cargo_bin("ocgen")
            .unwrap()
            .args(["doctor", "--yes"])
            .arg(dir.path())
            .assert()
            .success();
        let after = Project::load_state(dir.path()).unwrap();
        for c in after.plan_changes(dir.path()).unwrap() {
            assert_eq!(c.kind, ChangeKind::Unchanged, "{target:?} {}", c.rel);
        }
        for rel in &changed {
            let text = read(dir.path(), rel);
            assert!(
                text.contains("\"attribution\"") || text.contains(EN) || text.contains(UK),
                "{rel}:\n{text}"
            );
        }
    }
}
